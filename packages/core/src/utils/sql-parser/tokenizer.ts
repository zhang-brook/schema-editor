// Compound keywords (multi-word combinations, used to merge adjacent KEYWORDs during tokenization)
const COMPOUND_KEYWORDS: Record<string, string> = {
  'IF NOT EXISTS': 'IF_NOT_EXISTS',
  'OR REPLACE': 'OR_REPLACE',
  'PRIMARY KEY': 'PRIMARY_KEY',
  'FOREIGN KEY': 'FOREIGN_KEY',
  'CHARACTER SET': 'CHARACTER_SET',
  'DOUBLE PRECISION': 'DOUBLE_PRECISION',
  'NOT NULL': 'NOT_NULL',
  'AUTO INCREMENT': 'AUTO_INCREMENT',
  'GENERATED ALWAYS': 'GENERATED_ALWAYS',
  'GENERATED BY DEFAULT': 'GENERATED_BY_DEFAULT',
  'AS IDENTITY': 'AS_IDENTITY',
  'DEFAULT CHARACTER SET': 'DEFAULT_CHARSET',
  'DEFAULT CHARSET': 'DEFAULT_CHARSET',
  'DEFAULT COLLATE': 'DEFAULT_COLLATE',
  'ON UPDATE': 'ON_UPDATE',
  'NO ACTION': 'NO_ACTION',
  'SET NULL': 'SET_NULL',
  'ROW FORMAT': 'ROW_FORMAT',
  'WITHOUT TIME ZONE': 'WITHOUT_TZ',
  'WITH TIME ZONE': 'WITH_TZ',
}

/** Checks whether a string is an SQL keyword */
export function isKeyword(word: string): boolean {
  return KEYWORDS.has(word.toUpperCase())
}

// ===== Tokenizer state machine =====

export function tokenize(input: string): Token[] {
  const tokens: Token[] = []
  let pos = 0
  let line = 1
  let column = 1
  const len = input.length

  function advance(n = 1): void {
    pos += n
    column += n
  }

  function peek(offset = 0): string {
    return pos + offset < len ? input[pos + offset]! : ''
  }

  // oxlint-disable-next-line no-unused-vars
  function peekAhead(n: number): string {
    return pos + n < len ? input.substring(pos, pos + n) : ''
  }

  function pushToken(type: TokenType, value: string, startLine: number, startColumn: number): void {
    tokens.push({ type, value, line: startLine, column: startColumn })
  }

  while (pos < len) {
    const ch = input[pos]!
    const startLine = line
    const startColumn = column

    // Whitespace
    if (ch === ' ' || ch === '\t' || ch === '\r') {
      advance()
      continue
    }

    // Newline
    if (ch === '\n') {
      line++
      column = 1
      advance()
      continue
    }

    // Line comment --
    if (ch === '-' && peek(1) === '-' && (peek(2) === ' ' || peek(2) === '\t' || peek(2) === '\n' || peek(2) === '\r' || peek(2) === '' || peek(2) === '-')) {
      let value = ''
      advance(2) // skip --
      while (pos < len && input[pos] !== '\n') {
        value += input[pos]!
        advance()
      }
      pushToken(TokenType.COMMENT_LINE, value.trim(), startLine, startColumn)
      continue
    }

    // Block comment /* ... */
    if (ch === '/' && peek(1) === '*') {
      let value = ''
      advance(2) // skip /*
      let depth = 1
      while (pos < len && depth > 0) {
        if (input[pos] === '*' && peek(1) === '/') {
          depth--
          advance(2)
        } else if (input[pos] === '/' && peek(1) === '*') {
          depth++
          value += '/*'
          advance(2)
        } else {
          if (input[pos] === '\n') { line++; column = 1 }
          value += input[pos]!
          advance()
        }
      }
      pushToken(TokenType.COMMENT_BLOCK, value.trim(), startLine, startColumn)
      continue
    }

    // Backtick identifier `...`
    if (ch === '`') {
      let value = ''
      advance() // skip opening `
      while (pos < len) {
        const c = input[pos]!
        if (c === '`') {
          if (peek(1) === '`') {
            value += '`'
            advance(2)
          } else {
            advance() // skip closing `
            break
          }
        } else {
          if (c === '\n') { line++; column = 1 }
          value += c
          advance()
        }
      }
      pushToken(TokenType.BACKTICK_ID, value, startLine, startColumn)
      continue
    }

    // Double-quoted identifier "..."
    if (ch === '"') {
      let value = ''
      advance() // skip opening "
      while (pos < len) {
        const c = input[pos]!
        if (c === '"') {
          if (peek(1) === '"') {
            value += '"'
            advance(2)
          } else {
            advance() // skip closing "
            break
          }
        } else {
          if (c === '\n') { line++; column = 1 }
          value += c
          advance()
        }
      }
      pushToken(TokenType.DOUBLEQUOTE_ID, value, startLine, startColumn)
      continue
    }

    // Single-quoted string '...'
    if (ch === "'") {
      let value = ''
      advance() // skip opening '
      while (pos < len) {
        const c = input[pos]!
        if (c === "'") {
          if (peek(1) === "'") {
            value += "'"
            advance(2)
          } else {
            advance() // skip closing '
            break
          }
        } else {
          if (c === '\n') { line++; column = 1 }
          value += c
          advance()
        }
      }
      pushToken(TokenType.STRING, value, startLine, startColumn)
      continue
    }

    // PostgreSQL escape string E'...'
    if ((ch === 'E' || ch === 'e') && peek(1) === "'") {
      let value = ''
      advance(2) // skip E'
      while (pos < len) {
        const c = input[pos]!
        if (c === "'") {
          if (peek(1) === "'") {
            value += "'"
            advance(2)
          } else {
            advance()
            break
          }
        } else if (c === '\\' && peek(1) !== undefined) {
          // Keep escape sequences in value
          value += '\\' + peek(1)
          advance(2)
        } else {
          if (c === '\n') { line++; column = 1 }
          value += c
          advance()
        }
      }
      pushToken(TokenType.STRING, value, startLine, startColumn)
      continue
    }

    // PostgreSQL dollar-quoted string $tag$...$tag$
    if (ch === '$') {
      // Find the tag
      let tagEnd = pos + 1
      while (tagEnd < len && input[tagEnd] !== '$') {
        tagEnd++
      }
      if (tagEnd < len) {
        const tag = input.substring(pos, tagEnd + 1) // e.g. $tag$
        // Search for matching closing tag
        let searchPos = tagEnd + 1
        while (searchPos < len) {
          if (input.substring(searchPos, searchPos + tag.length) === tag) {
            const value = input.substring(tagEnd + 1, searchPos)
            // Count newlines in the entire dollar-quoted string
            const dollarStr = input.substring(pos, searchPos + tag.length)
            for (let i = 0; i < dollarStr.length; i++) {
              if (dollarStr[i] === '\n') { line++; column = 1 }
            }
            pos = searchPos + tag.length
            column = startColumn // approximate
            pushToken(TokenType.STRING, value, startLine, startColumn)
            break
          }
          searchPos++
        }
        if (searchPos >= len) {
          // Unclosed dollar quote — treat as symbol
          pushToken(TokenType.SYMBOL, '$', startLine, startColumn)
          advance()
          continue
        }
        continue
      }
    }

    // Number
    if ((ch >= '0' && ch <= '9') || (ch === '.' && peek(1) >= '0' && peek(1) <= '9')) {
      let value = ''
      while (pos < len && input[pos]! >= '0' && input[pos]! <= '9') {
        value += input[pos]!
        advance()
      }
      if (input[pos] === '.' && peek(1) >= '0' && peek(1) <= '9') {
        value += '.'
        advance()
        while (pos < len && input[pos]! >= '0' && input[pos]! <= '9') {
          value += input[pos]!
          advance()
        }
      }
      pushToken(TokenType.NUMBER, value, startLine, startColumn)
      continue
    }

    // Symbol
    if ('(),;=.'.includes(ch)) {
      pushToken(TokenType.SYMBOL, ch, startLine, startColumn)
      advance()
      continue
    }

    // PostgreSQL type cast ::
    if (ch === ':' && peek(1) === ':') {
      pushToken(TokenType.SYMBOL, '::', startLine, startColumn)
      advance(2)
      continue
    }

    // Identifier / keyword
    if ((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || ch === '_') {
      let value = ''
      while (pos < len) {
        const c = input[pos]!
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c === '_') {
          value += c
          advance()
        } else {
          break
        }
      }

      // Check whether it is a keyword (case-insensitive)
      if (KEYWORDS.has(value.toUpperCase())) {
        pushToken(TokenType.KEYWORD, value.toUpperCase(), startLine, startColumn)
      } else {
        pushToken(TokenType.IDENTIFIER, value, startLine, startColumn)
      }
      continue
    }

    // Unknown character — skip (lenient mode)
    advance()
  }

  // Append EOF
  pushToken(TokenType.EOF, '', line, column)

  return tokens
}

/**
 * Merges adjacent KEYWORD tokens into compound keyword tokens
 * e.g. NOT + NULL → NOT_NULL (a compound keyword becomes a single KEYWORD token)
 *      DOUBLE + PRECISION → DOUBLE_PRECISION
 */
export function mergeCompoundKeywords(tokens: Token[]): Token[] {
  const result: Token[] = []
  let i = 0

  while (i < tokens.length) {
    // Try to match a compound keyword (2-3 consecutive KEYWORDs)
    let merged = false

    // Try 3-word combinations
    if (i + 2 < tokens.length) {
      const three = `${tokens[i]!.value} ${tokens[i + 1]!.value} ${tokens[i + 2]!.value}`
      if (COMPOUND_KEYWORDS[three]) {
        result.push({
          type: TokenType.KEYWORD,
          value: COMPOUND_KEYWORDS[three]!,
          line: tokens[i]!.line,
          column: tokens[i]!.column,
        })
        i += 3
        merged = true
      }
    }

    // Try 2-word combinations
    if (!merged && i + 1 < tokens.length) {
      const two = `${tokens[i]!.value} ${tokens[i + 1]!.value}`
      if (COMPOUND_KEYWORDS[two]) {
        result.push({
          type: TokenType.KEYWORD,
          value: COMPOUND_KEYWORDS[two]!,
          line: tokens[i]!.line,
          column: tokens[i]!.column,
        })
        i += 2
        merged = true
      }
    }

    if (!merged) {
      result.push(tokens[i]!)
      i++
    }
  }

  return result
}

/**
 * Performs full lexical analysis on the token stream: tokenize + compound keyword merging
 */
export function lex(input: string): Token[] {
  const tokens = tokenize(input)
  return mergeCompoundKeywords(tokens)
}
