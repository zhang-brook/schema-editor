/**
 * SQL dialect detector — heuristic scoring rules
 *
 * Positive score → PostgreSQL traits
 * Negative score → MySQL traits
 * Zero score → Unknown
 *
 * SQLite and PostgreSQL syntax overlap heavily (both use double-quoted identifiers),
 * so they cannot be distinguished by the token stream alone. SQLite-specific syntax
 * is therefore scored separately on the raw text (see {@link detectSqliteSignals}).
 */

import { lex, type Token, TokenType } from './tokenizer'
import type { SqlDialect } from '../sql-generator/shared'

export type DetectedDialect = SqlDialect | 'unknown'

/**
 * Scores SQLite-specific syntax signals.
 *
 * These tokens are not included in the tokenizer's keyword table (to avoid affecting
 * existing MySQL/PostgreSQL parsing), so case-insensitive matching is done directly
 * on the raw text.
 *
 * - `PRAGMA` / `AUTOINCREMENT` / `WITHOUT ROWID` are unique to SQLite and carry the highest weight
 * - `STRICT` table option and `INTEGER PRIMARY KEY` (rowid alias form) are weak signals
 */
function detectSqliteSignals(sql: string): number {
  let sqlite = 0
  if (/\bPRAGMA\b/i.test(sql)) sqlite += 3
  if (/\bAUTOINCREMENT\b/i.test(sql)) sqlite += 3
  if (/\bWITHOUT\s+ROWID\b/i.test(sql)) sqlite += 3
  if (/\bSTRICT\b/i.test(sql)) sqlite += 1
  if (/\bINTEGER\s+PRIMARY\s+KEY\b/i.test(sql)) sqlite += 1
  return sqlite
}

/**
 * Detects the dialect from raw SQL text
 */
export function detectDialect(sql: string): DetectedDialect {
  const sqliteScore = detectSqliteSignals(sql)
  const tokens = lex(sql)
  return detectDialectFromTokens(tokens, sqliteScore)
}

/**
 * Detects the dialect from a token stream
 * @param tokens Token stream
 * @param sqliteScore SQLite-specific syntax score (computed by {@link detectSqliteSignals}; treated as 0 when omitted)
 */
export function detectDialectFromTokens(tokens: Token[], sqliteScore = 0): DetectedDialect {
  let score = 0

  // Collect the values of all KEYWORD tokens (for batch detection)
  const keywords = new Set<string>()
  const allValues: string[] = []
  let hasBacktickId = false
  let hasDoubleQuoteId = false
  let hasEngine = false
  // oxlint-disable-next-line no-unused-vars
  let insideCreateTable = false

  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i]!

    // Track the quoting style
    if (t.type === TokenType.BACKTICK_ID) {
      hasBacktickId = true
    }
    if (t.type === TokenType.DOUBLEQUOTE_ID) {
      hasDoubleQuoteId = true
    }

    if (t.type === TokenType.KEYWORD) {
      keywords.add(t.value)
      allValues.push(t.value)
    } else {
      allValues.push(t.value)
    }

    // Track whether we are inside CREATE TABLE
    if (t.type === TokenType.KEYWORD && t.value === 'CREATE') {
      // Check the following token
      if (tokens[i + 1]?.value === 'TABLE' || tokens[i + 1]?.value === 'OR_REPLACE') {
        insideCreateTable = true
      }
    }
    if (t.type === TokenType.SYMBOL && t.value === ';') {
      insideCreateTable = false
    }

    // ENGINE= only appears in the external option section after CREATE TABLE
    if (t.type === TokenType.KEYWORD && t.value === 'ENGINE') {
      hasEngine = true
    }
  }

  // ===== PostgreSQL traits (positive score) =====

  // GENERATED ALWAYS AS IDENTITY / GENERATED BY DEFAULT AS IDENTITY (weight +3)
  if (keywords.has('GENERATED_ALWAYS') || keywords.has('GENERATED_BY_DEFAULT') || keywords.has('AS_IDENTITY')) {
    score += 3
  }

  // SERIAL / BIGSERIAL / SMALLSERIAL (weight +3)
  if (keywords.has('SERIAL') || keywords.has('BIGSERIAL') || keywords.has('SMALLSERIAL')) {
    score += 3
  }

  // :: type cast (weight +2)
  for (let i = 0; i < tokens.length; i++) {
    if (tokens[i]!.type === TokenType.SYMBOL && tokens[i]!.value === '::') {
      score += 2
      break
    }
  }

  // DOUBLE PRECISION (weight +1)
  if (keywords.has('DOUBLE_PRECISION')) {
    score += 1
  }

  // Double-quoted identifiers + no ENGINE clause (weight +2)
  if (hasDoubleQuoteId && !hasEngine) {
    score += 2
  }

  // Double-quoted identifiers only (no backticks at all) (weight +1)
  if (hasDoubleQuoteId && !hasBacktickId) {
    score += 1
  }

  // CREATE SCHEMA (weight +1)
  const allText = allValues.join(' ')
  if (/\bCREATE\s+SCHEMA\b/i.test(allText)) {
    score += 1
  }

  // COMMENT ON TABLE/COLUMN (weight +1)
  if (keywords.has('COMMENT') && /\bCOMMENT\s+ON\b/i.test(allText)) {
    score += 1
  }

  // PostgreSQL-specific types
  if (keywords.has('JSONB') || keywords.has('BYTEA') || keywords.has('INET') ||
      keywords.has('CIDR') || keywords.has('MACADDR') || keywords.has('TIMESTAMPTZ')) {
    score += 2
  }

  // BOOLEAN as a type (in MySQL, BOOLEAN is a TINYINT(1) alias and less common)
  if (keywords.has('BOOLEAN') || keywords.has('BOOL')) {
    score += 0 // Neutral, no score adjustment
  }

  // ===== MySQL traits (negative score) =====

  // Backtick identifiers (weight -2)
  if (hasBacktickId) {
    score -= 2
  }

  // ENGINE= (weight -3)
  if (hasEngine) {
    score -= 3
  }

  // AUTO_INCREMENT (weight -3)
  if (keywords.has('AUTO_INCREMENT')) {
    score -= 3
  }

  // TINYINT as a column type (weight -2)
  if (keywords.has('TINYINT')) {
    score -= 2
  }

  // ENUM / SET types (weight -2)
  if (keywords.has('ENUM') || keywords.has('SET')) {
    score -= 2
  }

  // ON UPDATE CURRENT_TIMESTAMP (weight -1)
  if (keywords.has('ON_UPDATE')) {
    score -= 1
  }

  // CHARACTER SET / CHARSET / COLLATE as table options (weight -1)
  if (keywords.has('CHARACTER_SET') || keywords.has('DEFAULT_CHARSET') || keywords.has('DEFAULT_COLLATE')) {
    score -= 1
  }

  // MySQL-specific types
  if (keywords.has('MEDIUMINT') || keywords.has('MEDIUMTEXT') || keywords.has('LONGTEXT') ||
      keywords.has('TINYTEXT') || keywords.has('YEAR') || keywords.has('LONGBLOB') ||
      keywords.has('MEDIUMBLOB') || keywords.has('TINYBLOB') || keywords.has('GEOMETRY')) {
    score -= 2
  }

  // UNSIGNED / ZEROFILL (weight -1)
  if (keywords.has('UNSIGNED') || keywords.has('ZEROFILL')) {
    score -= 1
  }

  // ===== Decision =====
  // SQLite and PostgreSQL share a lot of common syntax; classify as SQLite only when SQLite-specific signals are strong enough to outweigh the PG/MySQL signals
  if (sqliteScore >= 3 && sqliteScore >= Math.abs(score)) return 'sqlite'
  if (score >= 3) return 'postgresql'
  if (score <= -3) return 'mysql'

  // Edge case: when no clear traits are present
  if (score > 0) return 'postgresql'
  if (score < 0) return 'mysql'

  return 'unknown'
}
